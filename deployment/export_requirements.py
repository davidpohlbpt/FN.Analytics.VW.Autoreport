"""Generate requirements-docker.txt from poetry.lock.

Only the main dependency group is exported (no test/docs/dev). ``pycore`` is replaced
by the vendored wheel in ./vendor so that the Docker build needs no git credentials.
Windows-only and PyPy-only markers are dropped because the image is Linux/CPython.

Usage (from the repository root):
    python deployment/export_requirements.py
"""

from __future__ import annotations

import pathlib
import re
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[1]
LOCK = ROOT / "poetry.lock"
PYPROJECT = ROOT / "pyproject.toml"
OUTPUT = ROOT / "requirements-docker.txt"
VENDOR = ROOT / "vendor"

EXTRAS = {"pycore": {"azure", "webapi"}}
DROP_MARKERS = (
    'sys_platform == "win32"',
    'platform_system == "Windows"',
    'implementation_name == "pypy"',
)


def _norm(name: str) -> str:
    """PEP 503 normalisation: case-insensitive, '-', '_' and '.' are equivalent."""
    return re.sub(r"[-_.]+", "-", name).lower()


def _dependency_names(package: dict, extras: set[str]) -> list[str]:
    names = []
    for name, spec in package.get("dependencies", {}).items():
        specs = spec if isinstance(spec, list) else [spec]
        for entry in specs:
            marker = entry.get("markers", "") if isinstance(entry, dict) else ""
            if any(m in marker for m in DROP_MARKERS):
                continue
            if "extra ==" in marker:
                wanted = re.findall(r'extra == "([^"]+)"', marker)
                if not any(e in extras for e in wanted):
                    continue
            if re.search(r'python_version < "3\.(\d+)"', marker):
                minor = int(re.search(r'python_version < "3\.(\d+)"', marker).group(1))
                if minor <= 12:
                    continue
            names.append(_norm(name))
    for extra in extras:
        for item in package.get("extras", {}).get(extra, []):
            names.append(_norm(re.split(r"[\s\[(<>=!~;]", item)[0]))
    return names


def main() -> int:
    lock = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    pyproject = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    packages = {_norm(p["name"]): p for p in lock["package"]}
    roots = [_norm(n) for n in pyproject["tool"]["poetry"]["dependencies"] if n != "python"]

    wanted: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in wanted:
            continue
        if name not in packages:
            print(f"warning: {name} not in poetry.lock, skipped", file=sys.stderr)
            continue
        wanted.add(name)
        stack.extend(_dependency_names(packages[name], EXTRAS.get(name, set())))

    wheels = sorted(VENDOR.glob("pycore-*.whl"))
    if "pycore" in wanted and not wheels:
        print("error: no pycore wheel in ./vendor (see vendor/README.md)", file=sys.stderr)
        return 1

    lines = ["# Generated by deployment/export_requirements.py from poetry.lock -- do not edit by hand"]
    for name in sorted(wanted):
        if name == "pycore":
            lines.append(f"./vendor/{wheels[-1].name}")
        else:
            lines.append(f"{packages[name]['name']}=={packages[name]['version']}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.name} with {len(lines) - 1} pins")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
